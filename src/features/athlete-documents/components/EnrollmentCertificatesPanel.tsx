import { useCallback, useEffect, useState } from "react";
import { Award, Download } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { EmptyState } from "@/components/common/EmptyState";
import { useApiErrorHandler } from "@/feedback/useApiErrorHandler";
import { formatDateForDisplay } from "@/lib/dateUtils";

import { athleteDocumentsApi, type CertifiableEnrollment } from "../api/athleteDocumentsApi";

const STATUS_LABELS: Record<string, string> = {
  active: "Activa",
  completed: "Finalizada",
};

interface Props {
  athleteId: number;
  /** Render without the outer card (e.g. inside another card). */
  bare?: boolean;
}

/**
 * Enrollment certificates (Req 2, "constancias de inscripción"): lists the
 * athlete's certifiable enrollments (active/completed) and downloads the PDF
 * generated by the backend.
 */
export default function EnrollmentCertificatesPanel({ athleteId, bare = false }: Props) {
  const { handleError } = useApiErrorHandler();
  const [items, setItems] = useState<CertifiableEnrollment[]>([]);
  const [loading, setLoading] = useState(true);
  const [busyId, setBusyId] = useState<number | null>(null);

  const load = useCallback(async () => {
    try {
      setItems(await athleteDocumentsApi.certificates(athleteId));
    } catch (err) {
      handleError(err);
    } finally {
      setLoading(false);
    }
  }, [athleteId, handleError]);

  useEffect(() => {
    setLoading(true);
    void load();
  }, [load]);

  const handleDownload = async (cert: CertifiableEnrollment) => {
    setBusyId(cert.enrollment_id);
    try {
      await athleteDocumentsApi.downloadCertificate(cert);
      void load(); // refresh "last issued" code/date
    } catch (err) {
      handleError(err);
    } finally {
      setBusyId(null);
    }
  };

  const body = loading ? (
    <Skeleton className="h-24 w-full" />
  ) : items.length === 0 ? (
    <EmptyState
      icon={Award}
      title="Sin inscripciones certificables"
      description="Las constancias se generan para inscripciones activas o finalizadas."
    />
  ) : (
    <ul className="divide-y divide-divider">
      {items.map((cert) => (
        <li
          key={cert.enrollment_id}
          className="flex flex-col gap-3 py-3 sm:flex-row sm:items-center sm:justify-between"
        >
          <div className="min-w-0 space-y-1">
            <div className="flex flex-wrap items-center gap-2">
              <p className="font-medium text-text">{cert.program_name}</p>
              <Badge variant={cert.status === "active" ? "success" : "outline"}>
                {STATUS_LABELS[cert.status] ?? cert.status}
              </Badge>
            </div>
            <p className="text-sm text-muted">
              Desde {formatDateForDisplay(cert.start_date)}
              {cert.end_date ? ` hasta ${formatDateForDisplay(cert.end_date)}` : ""}
            </p>
            {cert.last_code && (
              <p className="text-xs text-faint">
                Última constancia: {cert.last_code}
                {cert.last_issued_at ? ` · ${formatDateForDisplay(cert.last_issued_at)}` : ""}
              </p>
            )}
          </div>
          <Button
            size="sm"
            onClick={() => void handleDownload(cert)}
            disabled={busyId === cert.enrollment_id}
          >
            <Download className="h-4 w-4" />
            {busyId === cert.enrollment_id ? "Generando…" : "Descargar constancia"}
          </Button>
        </li>
      ))}
    </ul>
  );

  if (bare) return body;
  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-base">
          <Award className="h-4 w-4 text-primary" />
          Constancias de inscripción
        </CardTitle>
        <p className="text-sm text-muted">
          Descarga en PDF la constancia oficial del club para cada inscripción.
        </p>
      </CardHeader>
      <CardContent>{body}</CardContent>
    </Card>
  );
}
