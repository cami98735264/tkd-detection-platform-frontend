// Security headers for every document/asset the edge serves (single source of
// truth). Applied by the Worker / Pages Function to the responses they return
// and written to `public/_headers` at build time (scripts/build-lib.mjs) so the
// static-asset layer — which serves most files without invoking the Worker —
// sends exactly the same headers.
//
// Proxied backend responses (/api, /ws, /media) are NOT modified: they are the
// backend's own responses and a 101 WebSocket upgrade must pass through as-is.

/** Directives of the Content-Security-Policy, in order. */
export const CSP_DIRECTIVES: ReadonlyArray<readonly [string, string]> = [
  ["default-src", "'self'"],
  // All JS is first-party (bundles + the self-hosted MediaPipe loader). No
  // inline scripts: the theme bootstrap lives in /theme-init.js.
  // 'wasm-unsafe-eval' only allows compiling WebAssembly (MediaPipe), not eval().
  ["script-src", "'self' 'wasm-unsafe-eval'"],
  // Radix, sonner and FullCalendar inject inline <style>/style attributes.
  ["style-src", "'self' 'unsafe-inline'"],
  // data: for QR codes / jspdf, blob: for previews of uploaded files.
  ["img-src", "'self' data: blob:"],
  ["font-src", "'self'"],
  // Same-origin API + WebSocket (the edge proxies /api and /ws). Self-hosted
  // MediaPipe wasm/model are fetched from this origin too.
  ["connect-src", "'self'"],
  // Recorded kick video is previewed from a blob: URL.
  ["media-src", "'self' blob:"],
  ["worker-src", "'self' blob:"],
  ["object-src", "'none'"],
  ["base-uri", "'self'"],
  ["form-action", "'self'"],
  ["frame-ancestors", "'none'"],
];

export const CONTENT_SECURITY_POLICY = CSP_DIRECTIVES.map(([k, v]) => `${k} ${v}`).join("; ");

export const SECURITY_HEADERS: Readonly<Record<string, string>> = {
  "Content-Security-Policy": CONTENT_SECURITY_POLICY,
  // Legacy equivalent of frame-ancestors 'none' for older browsers.
  "X-Frame-Options": "DENY",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  // Camera is needed by the technical-evaluation recorder on this origin only.
  "Permissions-Policy":
    "camera=(self), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
  "Cross-Origin-Opener-Policy": "same-origin",
};

/**
 * Return a copy of `response` with the security headers set. Responses from
 * `fetch`/`env.ASSETS` have immutable headers, hence the copy.
 */
export function withSecurityHeaders(response: Response): Response {
  // 101 Switching Protocols can't be re-wrapped and never carries a document.
  if (response.status === 101 || response.webSocket) return response;
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) headers.set(name, value);
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

/**
 * Render the rules for the static-asset `_headers` file (Workers Static Assets
 * and Pages share the format). Long-lived caching for the version-pinned
 * MediaPipe runtime and model.
 */
export function renderHeadersFile(): string {
  const lines = [
    "# Generated by scripts/build-lib.mjs from src/edge/securityHeaders.ts — do not edit.",
    "/*",
  ];
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) lines.push(`  ${name}: ${value}`);
  lines.push("", "/vendor/*", "  Cache-Control: public, max-age=31536000, immutable");
  lines.push("", "/models/*", "  Cache-Control: public, max-age=31536000, immutable");
  return lines.join("\n") + "\n";
}
